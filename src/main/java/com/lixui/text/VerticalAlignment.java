package com.lixui.text;

/**
 * Vertical placement of a text block relative to its anchor point.
 * The anchor is the top edge, the vertical center or the bottom edge of the block.
 */
public enum VerticalAlignment {
    /** The anchor point is the top edge of the text block. */
    TOP,
    /** The anchor point is the vertical center of the text block. */
    CENTER,
    /** The anchor point is the bottom edge of the text block. */
    BOTTOM
}
